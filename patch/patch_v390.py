# Add procedural starter melodic packs for testing.
if 'HUMANDETECT_MELODIC_STARTER_PACKS_V390' not in mt:
    mt += r'''

// HUMANDETECT_MELODIC_STARTER_PACKS_V390
function installMelodicStarterPack(id,name,type,rootMidi,partials,decay,attack=.01){
  const dir=path.join(instrumentRoot(),id);fs.mkdirSync(dir,{recursive:true});
  const sr=48000,dur=type==='pad'||type==='strings'?4.0:2.5,n=Math.floor(sr*dur),f=440*Math.pow(2,(rootMidi-69)/12),a=new Float32Array(n);
  for(let i=0;i<n;i++){
    const t=i/sr,atk=Math.min(1,t/attack),rel=Math.exp(-t/decay);let x=0;
    for(let k=0;k<partials.length;k++)x+=Math.sin(2*Math.PI*f*(k+1)*t)*partials[k];
    if(type==='pad'||type==='strings')x*=Math.min(1,t/.18)*Math.min(1,(dur-t)/.5);
    a[i]=x*atk*rel*.52;
  }
  writeMonoWav(path.join(dir,'sample.wav'),a,sr);
  fs.writeFileSync(path.join(dir,'instrument.json'),JSON.stringify({
    id,name,type,version:'1.0.0',license:'Procedural starter pack generated by HumanDetect',rootMidi,sample:'sample.wav',
    tags:['starter',type,'procedural'],engine:'single-note-resample-v1'
  },null,2));
}
function installExtendedStarterPacks(){
  installMelodicStarterPack('humandetect-starter-keys','HumanDetect Starter Keys','keys',60,[1,.42,.18,.08],1.45,.006);
  installMelodicStarterPack('humandetect-starter-guitar','HumanDetect Starter Guitar','guitar',52,[1,.55,.25,.12,.06],1.0,.004);
  installMelodicStarterPack('humandetect-starter-synth','HumanDetect Starter Synth Lead','synth',60,[1,.7,.32,.18],1.8,.003);
  installMelodicStarterPack('humandetect-starter-pad','HumanDetect Starter Pad','pad',60,[1,.35,.2,.1],6.0,.15);
  installMelodicStarterPack('humandetect-starter-strings','HumanDetect Starter Strings','strings',57,[1,.5,.22,.1,.05],5.5,.12);
  return listInstrumentPacks();
}
ipcMain.handle('instrument-install-extended-starter',async()=>{try{return {success:true,packs:installExtendedStarterPacks()};}catch(e){return {success:false,error:e.message};}});
'''
